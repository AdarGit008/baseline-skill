#!/usr/bin/env node
// Regenerates the two derived regions of docs/REFERENCE.md — the rule table and the check-kind
// list — from the rule set itself (loadRules()) and the evaluator registry (CHECK_KINDS).
// Nothing in the regions is typed by hand: ids, titles, severities, packs, scopes and the
// per-category grouping all come from rules/*.json, in rules.json module order and the
// report's category order, so the table cannot drift from the runner (v3 V32/V33: no
// count is a literal anywhere — this file prints none, and derives the grouping instead).
//
// Usage:
//   node docs/assets/gen-reference-rules.mjs          # rewrite the regions in place
//   node docs/assets/gen-reference-rules.mjs --check  # exit 1 if docs/REFERENCE.md is behind the rule set
//
// Rerun after any change to rules/, rules.json, CATS in src/report.mjs, or CHECK_KINDS in
// src/evaluators.mjs (a new family — e.g. PLUG — lands in the table by running this once).
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { loadRules } from '../../src/rules.mjs'
import { CATS } from '../../src/report.mjs'
import { CHECK_KINDS } from '../../src/evaluators.mjs'

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', '..')
const TARGET = path.join(ROOT, 'docs', 'REFERENCE.md')
const CHECK = process.argv.includes('--check')
const SELF = 'docs/assets/gen-reference-rules.mjs'

const begin = (name) => `<!-- baseline:${name} begin — generated by ${SELF}; edit rules/*.json (or the glosses in that script), then rerun it -->`
const end = (name) => `<!-- baseline:${name} end -->`

// ---------- the rule table ----------
// 'none' is not a weaker tier — it is the ABSENCE of a severity claim, carried by a rule
// whose check cannot produce a verdict (kind 'frozen'). It gets its own glyph so the table
// never reads it as a quieter blocker.
const SEV = { blocker: '🔴 blocker', warn: '🟡 warn', none: '⚪ frozen · no severity' }
const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim()
const scopeOf = (r) => {
  const t = r.applies_to === 'all' || r.applies_to == null ? 'all' : (Array.isArray(r.applies_to) ? r.applies_to.join(', ') : String(r.applies_to))
  return r.tool ? `${t} · tool: ${r.tool}` : t
}
function rulesTable(rules) {
  const cats = [...Object.keys(CATS), ...new Set(rules.map(r => r.category).filter(c => !(c in CATS)))]
  const out = []
  for (const cat of cats) {
    const group = rules.filter(r => r.category === cat)
    if (!group.length) continue
    out.push(`### ${CATS[cat] ?? cat}`, '')
    out.push('| ID | Rule | Severity | Pack | Scope |', '|---|---|---|---|---|')
    for (const r of group) out.push(`| ${cell(r.id)} | ${cell(r.title)} | ${SEV[r.severity] ?? cell(r.severity)} | ${r.pack ? cell(r.pack) : '—'} | ${cell(scopeOf(r))} |`)
    out.push('')
  }
  return out.join('\n').trimEnd()
}

// ---------- the check kinds ----------
// A gloss is documentation for a kind that EXISTS in the registry; a gloss whose kind has
// left the registry is dropped on regeneration, and a registered kind with no gloss still
// prints (by name), so the list is always exactly the registry.
const GLOSS = {
  'any-file': 'glob presence (`mode: absent`, `tracked_only`, `allow`)',
  'grep': 'regex present / absent / all over file contents (`tracked_only`)',
  'file-contains': 'the file exists AND matches',
  'any-of': 'pass if any alternative passes (recurses)',
  'implies': 'when the precondition holds, the consequent must (else n/a)',
  'command': 'run the configured bootstrap command (`repeat` for idempotence)',
  'md-links': 'relative markdown links resolve against each doc\'s own directory',
  'path-integrity': 'backticked paths named in docs still exist',
  'doc-freshness': 'a frontmatter review date inside the configured window',
  'doc-code-age': 'a doc does not lag the code it anchors by more than `doc_lag_days`',
  'graph-stamp-fresh': "the committed graphify stamp's content hashes still match the tracked code files — the check-pipeline face of `baseline trust verify`; the graph itself is never opened",
  'artifact-not-lagging': "a trust-circle member's TRACKED artifact was not committed before the newest commit under its configured source scope — an ordering, with no day threshold; same commit passes",
  'stamp-not-lagging': 'the commit a RECORDED-ONLY stamp names is not behind the newest commit under its source scope — the claim is ordered, never verified, and every verdict says so',
  'frozen': 'structurally incapable of a verdict: always n/a, silent to humans, and the only kind that may claim no severity (a tool that does not exist yet)',
  'orient-entrypoint': "the committed `.baseline/orient.sh` is BYTE-IDENTICAL to the one this baseline ships (`baseline trust wire` installs it) — identity, not existence; absence is n/a",
  'adr-status': 'every decision record carries a Status; superseded ones link forward',
  'adr-forward-link': 'every declared decision edge resolves to a file that exists',
  'adr-backlink': 'an amendment is declared at both ends',
  'adr-number-unique': 'no two decision records claim the same number',
  'required-files': 'a configured list of files exists and is non-empty',
  'config-nonempty': 'a configured key is set and non-empty',
  'version-consistency': 'the pinned runtime major agrees across `.nvmrc` / CI / Dockerfile / `engines`',
  'dockerfile-digest': '`FROM` lines pinned by `@sha256` (declares `tool: docker`)',
  'workflow-permissions': 'CI workflows grant a least-privilege token',
  'claims-field': 'every claim record carries the field',
  'claims-citations': 'claim citations resolve and support the claim',
  'descriptor': '`baseline.repo.json` is present',
  'descriptor-valid': 'a present descriptor schema-validates',
  'descriptor-change': 'a descriptor change carries its judgment in the same range (admit)',
  'records-scrub': 'landed records are scrub-clean at HEAD (blob content, never the worktree)',
  'forge-protection': 'merge protection on the default branch, read from the forge — n/a under `check` (forge not consulted)',
  'workflow-state': 'the reconcile workflow is alive at the forge — n/a under `check` (forge not consulted)',
  'plugin-presence': 'a plugin artifact exists and its gitignore state matches the `plugins` config — metadata only, never the content',
}
function kindsList() {
  const kinds = [...CHECK_KINDS].sort()
  return kinds.map(k => GLOSS[k] ? `- \`${k}\` — ${GLOSS[k]}` : `- \`${k}\``).join('\n')
}

// ---------- splice ----------
function splice(md, name, body) {
  const b = begin(name), e = end(name)
  const i = md.indexOf(b), j = md.indexOf(e)
  if (i < 0 || j < 0 || j < i) throw new Error(`docs/REFERENCE.md has no '${name}' region (expected the begin and end markers)`)
  return md.slice(0, i) + b + '\n\n' + body + '\n\n' + e + md.slice(j + e.length)
}

const { rules } = loadRules()
const current = fs.readFileSync(TARGET, 'utf8')
let next = splice(current, 'rules-table', rulesTable(rules))
next = splice(next, 'check-kinds', kindsList())

if (CHECK) {
  if (next !== current) { console.error(`docs/REFERENCE.md is behind the rule set — regenerate: node ${SELF}`); process.exit(1) }
  console.log('docs/REFERENCE.md rule table and check-kind list are current'); process.exit(0)
}
fs.writeFileSync(TARGET, next)
console.log(`wrote docs/REFERENCE.md: rule table (${rules.length} rows, ${new Set(rules.map(r => r.category)).size} categories) + check-kind list (${CHECK_KINDS.size} kinds)`)
